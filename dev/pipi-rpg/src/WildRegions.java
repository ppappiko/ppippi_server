    /** Places / restores / registers the three wild warp stones. Null when the warp-stone block (mod) is not registered yet. */
    String ensureStones() {
        Warps warps = plugin.warpSystem();
        if (warps == null) return "워프석 시스템이 꺼져 있습니다.";
        if (!warps.stoneAvailable()) return null;
        World w = world();
        if (w == null) return "야생 월드(" + plugin.wildWorldName() + ")를 찾지 못했습니다.";
        List<String> spots = plugin.data().getStringList(K_SPOTS);
        if (spots.size() < STONE_AT.length) {
            spots = new ArrayList<>();
            for (int[] s : STONE_AT) spots.add(spot(w, s[0], s[1]));
            if (!plugin.store(K_SPOTS, spots)) return "워프석 위치를 저장하지 못했습니다.";
        }
        List<TownMap.Stone> stones = new ArrayList<>();
        for (int i = 0; i < STONE_AT.length; i++) {
            String[] p = spots.get(i).split(",");
            int x = Integer.parseInt(p[0].trim()), y = Integer.parseInt(p[1].trim()), z = Integer.parseInt(p[2].trim());
            float yaw = (float) Math.toDegrees(Math.atan2(x, -z)); // face the origin
            stones.add(new TownMap.Stone(STONE_INFO[i][0], STONE_INFO[i][1], x, y, z, yaw));
        }
        String result = warps.ensureWildStones(w, stones, CATEGORY, true);
        if (result != null && !plugin.data().getBoolean(K_PLACED)) plugin.store(K_PLACED, true);
        return result == null ? null : result + " 위치: " + String.join(" / ", spots);
    }

    /** Startup: places the stones once (only when {@value #K_PLACED} is not set), retrying while the mod block is missing. */
    void scheduleStones(int attempt) {
        if (plugin.data().getBoolean(K_PLACED)) return;
        Bukkit.getScheduler().runTaskLater(plugin, () -> {
            if (plugin.data().getBoolean(K_PLACED)) return;
            String result;
            try { result = ensureStones(); }
            catch (RuntimeException ex) { plugin.getLogger().warning("야생 워프석 설치 실패: " + ex); return; }
            if (result == null) {
                if (attempt < 12) scheduleStones(attempt + 1);
                else plugin.getLogger().warning("야생 워프석: 워프석 블록(모드 pipifacilities)을 찾지 못했습니다. /pipilife maps wildstones 로 다시 시도하세요.");
            } else plugin.getLogger().info(result);
        }, 100L);
    }

    /**
     * Startup: the wild stones are public. Entries already in warps.yml (from before they were public) get {@code public: true},
     * and every public waypoint is registered for the players online now (later ones get it on join, {@link Warps}).
     */
    void publicStones() {
        Warps warps = plugin.warpSystem();
        if (warps == null) return;
        List<String> ids = new ArrayList<>();
        for (String[] s : STONE_INFO) ids.add(s[0]);
        int n = warps.makePublic(ids);
        if (n > 0) plugin.getLogger().info("야생 워프석 " + n + "개를 공개(public) 웨이포인트로 전환했습니다: " + ids);
    }

    /**
     * "x,y,z" of the cell a stone goes in: the nearest column (ring search within {@link #SPOT_R}) whose natural top is dry solid
     * ground with two free cells; grass/flowers there are removed. Otherwise (water, trees) a 3x3 stone-brick platform at the
     * nominal spot: on the water surface, or on top of the ground.
     */
    private static String spot(World w, int x0, int z0) {
        for (int cx = (x0 - SPOT_R) >> 4; cx <= (x0 + SPOT_R) >> 4; cx++) for (int cz = (z0 - SPOT_R) >> 4; cz <= (z0 + SPOT_R) >> 4; cz++) w.getChunkAt(cx, cz).load(true);
        for (int r = 0; r <= SPOT_R; r++)
            for (int dx = -r; dx <= r; dx++) for (int dz = -r; dz <= r; dz++) {
                if (Math.max(Math.abs(dx), Math.abs(dz)) != r) continue;
                int y = groundY(w, x0 + dx, z0 + dz);
                if (y == Integer.MIN_VALUE) continue;
                for (int k = 1; k <= 2; k++) {
                    Block b = w.getBlockAt(x0 + dx, y + k, z0 + dz);
                    if (!b.getType().isAir() && plant(b.getType())) b.setType(Material.AIR, false);
                }
                return (x0 + dx) + "," + (y + 1) + "," + (z0 + dz);
            }
        int top = w.getHighestBlockYAt(x0, z0, HeightMap.MOTION_BLOCKING_NO_LEAVES);
        Material m = w.getBlockAt(x0, top, z0).getType();
        int py = m == Material.WATER || m == Material.ICE || m == Material.LAVA ? top : top + 1;
        for (int dx = -1; dx <= 1; dx++) for (int dz = -1; dz <= 1; dz++) {
            w.getBlockAt(x0 + dx, py, z0 + dz).setType(Material.STONE_BRICKS, false);
            for (int k = 1; k <= 3; k++) w.getBlockAt(x0 + dx, py + k, z0 + dz).setType(Material.AIR, false);
        }
        return x0 + "," + (py + 1) + "," + z0;
    }

    /** Top natural ground y of a column, or MIN_VALUE when it is a tree, water/lava, or has no headroom. */
    private static int groundY(World w, int x, int z) {
        int top = w.getHighestBlockYAt(x, z, HeightMap.MOTION_BLOCKING_NO_LEAVES);
        for (int y = top; y > w.getMinHeight(); y--) {
            Material m = w.getBlockAt(x, y, z).getType();
            if (Tag.LOGS.isTagged(m) || m == Material.WATER || m == Material.LAVA || m == Material.ICE) return Integer.MIN_VALUE;
            if (m.isAir() || plant(m)) continue;
            if (!m.isSolid() || Tag.LEAVES.isTagged(m)) return Integer.MIN_VALUE;
            for (int h = 1; h <= 2; h++) {
                Material above = w.getBlockAt(x, y + h, z).getType();
                if (!above.isAir() && !plant(above)) return Integer.MIN_VALUE;
            }
            return y;
        }
        return Integer.MIN_VALUE;
    }

    private static boolean plant(Material m) {
        return !m.isSolid() && !Tag.LEAVES.isTagged(m) && m != Material.WATER && m != Material.LAVA
            && (Tag.FLOWERS.isTagged(m) || Tag.REPLACEABLE.isTagged(m) || Tag.SAPLINGS.isTagged(m));
    }

