    /** Parsed regions/<id>.bin (see dev/art/regions/lib.mjs exportRegion; PRG1 = no entrance, PRG2 = + boss entrance marker). */
    private static final class Layout {
        int w, d, y0, sx, sy, sz;
        int ex, ey, ez;          // boss-room entrance marker (local x/z, real y); ey == NO_ENTRANCE when the layout has none
        long crc;                // CRC32 of the resource file: a built region whose stored crc differs needs a rebuild
        float yaw;
        BlockData[] pal;
        byte[] cols;
        int[] start; // byte offset of each column (z * w + x)
    }

    private static Def def(String id) {
        for (Def d : DEFS) if (d.id().equalsIgnoreCase(id)) return d;
        return null;
    }

    private static int originX(Def d, Layout l) { return d.cx() - l.w / 2; }
    private static int originZ(Def d, Layout l) { return d.cz() - l.d / 2; }

    private Layout layout(Def d) {
        Layout cached = layouts.get(d.id());
        if (cached != null) return cached;
        try (InputStream res = plugin.getResource("regions/" + d.id() + ".bin")) {
            if (res == null) return null;
            byte[] file = res.readAllBytes();
            java.util.zip.CRC32 crc = new java.util.zip.CRC32();
            crc.update(file);
            DataInputStream in = new DataInputStream(new GZIPInputStream(new java.io.ByteArrayInputStream(file), 1 << 16));
            byte[] magic = new byte[4];
            in.readFully(magic);
            String format = new String(magic, java.nio.charset.StandardCharsets.US_ASCII);
            if (!"PRG1".equals(format) && !"PRG2".equals(format)) throw new IOException("bad magic " + format);
            Layout l = new Layout();
            l.crc = crc.getValue();
            l.w = in.readInt(); l.d = in.readInt(); l.y0 = in.readInt();
            int n = in.readUnsignedShort();
            l.pal = new BlockData[n];
            for (int i = 0; i < n; i++) {
                String s = TownMap.normalizeState(in.readUTF());
                try { l.pal[i] = Bukkit.createBlockData(s); }
                catch (IllegalArgumentException ex) { plugin.getLogger().warning("region " + d.id() + ": unknown block state " + s + " -> air"); l.pal[i] = Material.AIR.createBlockData(); }
            }
            l.sx = in.readInt(); l.sy = in.readInt(); l.sz = in.readInt(); l.yaw = in.readFloat();
            if ("PRG2".equals(format)) { l.ex = in.readInt(); l.ey = in.readInt(); l.ez = in.readInt(); }
            else l.ey = NO_ENTRANCE;
            ByteArrayOutputStream rest = new ByteArrayOutputStream(1 << 20);
            in.transferTo(rest);
            l.cols = rest.toByteArray();
            l.start = new int[l.w * l.d];
            int[] pos = {0};
            for (int c = 0; c < l.start.length; c++) {
                l.start[c] = pos[0];
                int runs = varint(l.cols, pos);
                for (int r = 0; r < runs * 2; r++) varint(l.cols, pos);
            }
            if (pos[0] != l.cols.length) throw new IOException("column data size mismatch " + pos[0] + " / " + l.cols.length);
            layouts.put(d.id(), l);
            return l;
        } catch (IOException | RuntimeException ex) {
            plugin.getLogger().severe("region " + d.id() + " layout load failed: " + ex);
            return null;
        }
    }

    private static int varint(byte[] b, int[] pos) {
        int v = 0, shift = 0;
        while (true) {
            int x = b[pos[0]++] & 0xff;
            v |= (x & 0x7f) << shift;
            if (x < 0x80) return v;
            shift += 7;
        }
    }

    private static String key(Def d, String k) { return "regions." + d.id() + "." + k; }

    /**
     * World location of the region's boss-room entrance marker block (a lodestone in the floor of the sealed sculk doorway at the
     * bottom of the entrance stairwell; a player standing on it is at y + 1). Block-centred x/z. Null when the id is unknown, the
     * wild world is missing or the layout has no entrance. The teleport into the boss world is not implemented yet.
     */
    Location entranceLocation(String id) {
        Def d = def(id);
        World w = world();
        if (d == null || w == null) return null;
        Layout l = layout(d);
        if (l == null || l.ey == NO_ENTRANCE) return null;
        return new Location(w, originX(d, l) + l.ex + .5, l.ey, originZ(d, l) + l.ez + .5);
    }

    /** Built with an older layout than the one in this jar (or before layouts were versioned): needs a rebuild. */
    private boolean outdated(Def d, Layout l) {
        if (l == null || !plugin.data().getBoolean(key(d, "built"))) return false;
        return !Long.toHexString(l.crc).equals(plugin.data().getString(key(d, "layout-crc")));
    }

    void visit(Player player, String id) {
        Def d = def(id);
        if (d == null) { player.sendMessage("/pipilife maps visit region <nw|ne|se>"); return; }
        World w = world();
        if (w == null) { player.sendMessage("야생 월드를 찾지 못했습니다."); return; }
        Layout l = layout(d);
        boolean built = plugin.data().getBoolean(key(d, "built"));
        int x, y, z;
        float yaw = 0;
        if (l != null) { x = originX(d, l) + l.sx; z = originZ(d, l) + l.sz; y = l.sy; yaw = l.yaw; }
        else { x = d.cx(); z = d.cz(); y = 0; }
        w.getChunkAt(x >> 4, z >> 4).load(true);
        if (!built || l == null) y = w.getHighestBlockYAt(x, z) + 1;
        player.teleport(new Location(w, x + .5, y, z + .5, yaw, 0));
        player.sendMessage("§a" + d.name() + " (" + x + ", " + z + ")" + (built ? "" : " §7— 아직 만들지 않았습니다: /pipilife maps buildregion " + d.id()));
    }

    void build(Player player, String id, boolean force) {
        if ("status".equalsIgnoreCase(id)) { status(player); return; }
        Def d = def(id);
        if (d == null) { player.sendMessage("/pipilife maps buildregion <nw|ne|se> [force] · /pipilife maps buildregion status"); return; }
        if (job != null) { player.sendMessage("§e" + job.d.id() + " 지역을 만드는 중입니다 (" + job.pct() + "%). 끝난 뒤 다시 실행하세요. 상태: /pipilife maps buildregion status"); return; }
        if (plugin.data().getBoolean(key(d, "built")) && !force) {
            if (outdated(d, layout(d))) {
                player.sendMessage("§e" + d.name() + ": 플러그인의 레이아웃이 새 버전입니다 — 다시 짓습니다 (기존 지형·건물은 새 지형으로 교체).");
                force = true;
            } else {
                player.sendMessage("§e" + d.name() + "은(는) 이미 만들어져 있습니다. 다시 지으려면 /pipilife maps buildregion " + d.id() + " force");
                return;
            }
        }
        String err = start(d, force, player, false);
        if (err != null) player.sendMessage("§c" + err);
    }

    /** Startup: resumes a build that was running when the server stopped ({@value #K_BUILDING}). */
    void scheduleResume() {
        String id = plugin.data().getString(K_BUILDING);
        if (id == null) return;
        Bukkit.getScheduler().runTaskLater(plugin, () -> {
            if (job != null) return;
            Def d = def(id);
            if (d == null || plugin.data().getBoolean(key(d, "built"))) { plugin.store(K_BUILDING, null); return; }
            String err;
            try { err = start(d, false, null, true); }
            catch (RuntimeException ex) { err = ex.toString(); }
            if (err != null) plugin.getLogger().warning("region " + id + " 건설 자동 재개 실패: " + err + " (/pipilife maps buildregion " + id + " 로 다시 시도)");
        }, 200L);
    }

    /** Plugin disable: stores the progress of a running build and removes its bar; it resumes on the next start. */
    void shutdown() {
        if (job != null) job.pause();
    }

    /** {@code /pipilife maps buildregion status}. */
    void status(Player player) {
        if (job == null) player.sendMessage("§e진행 중인 건설 없음");
        else player.sendMessage("§e건설 중: " + job.d.name() + " (" + job.d.id() + ") §f" + job.pct() + "% · " + job.ci + "/" + job.chunks.size()
            + " 청크 · 경과 " + clock(job.elapsedMs()) + " · 남은 시간 " + job.eta());
        for (Def d : DEFS) {
            String state;
            if (plugin.data().getBoolean(key(d, "built"))) state = outdated(d, layout(d))
                ? "§6건설 완료 (옛 레이아웃) — 새 레이아웃으로 다시 짓기 필요: /pipilife maps buildregion " + d.id() : "§a건설 완료";
            else if (job != null && job.d == d) state = "§e건설 중";
            else {
                int next = plugin.data().getInt(key(d, "next-chunk"), 0);
                state = next > 0 ? "§6중단됨 (" + next + " 청크까지, 다시 실행하면 이어서)" : "§7미건설";
            }
            player.sendMessage("§7- " + d.id() + " " + d.name() + ": " + state);
        }
    }

    private static String clock(long ms) {
        long s = Math.max(0, ms / 1000);
        return (s >= 60 ? s / 60 + "분 " : "") + s % 60 + "초";
    }

    /** Starts (or resumes) building {@code d}; returns an error message or null. */
    private String start(Def d, boolean force, Player issuer, boolean auto) {
        World w = world();
        if (w == null) return "야생 월드(" + plugin.wildWorldName() + ")를 찾지 못했습니다.";
        Layout l = layout(d);
        if (l == null) return "플러그인 안의 regions/" + d.id() + ".bin을 읽지 못했습니다.";
        if (force) { plugin.store(key(d, "built"), null); plugin.store(key(d, "next-chunk"), null); plugin.store(key(d, "elapsed-ms"), null); }
        plugin.store(K_BUILDING, d.id());
        job = new Job(d, l, w, issuer);
        job.begin(auto);
        job.runTaskTimer(plugin, 1, 1);
        return null;
    }

    @EventHandler
    public void opJoin(org.bukkit.event.player.PlayerJoinEvent e) {
        Job j = job;
        if (j == null || !e.getPlayer().isOp()) return;
        j.bar.addPlayer(e.getPlayer());
        e.getPlayer().sendMessage("§e[지역 건설] " + j.d.name() + " (" + j.d.id() + ") 건설 중 " + j.pct() + "% · 남은 시간 " + j.eta());
    }

    private final class Job extends BukkitRunnable {
        final Def d;
        final Layout l;
        final World w;
        final java.util.UUID issuer;
        final int ox, oz;
        final List<int[]> chunks = new ArrayList<>();
        final Map<Integer, CompletableFuture<?>> pending = new HashMap<>();
        int waitTicks; // ticks spent waiting for the current async chunk; Youer may never complete it, so fall back to a sync load
        Method async = asyncChunkMethod();
        final BossBar bar;
        final long startNanos = System.nanoTime(), baseMs;
        final int startCi;
        int ci, col = -1, lastTen, sinceSave, ticks;
        boolean ticket;
        long blocks;

        Job(Def d, Layout l, World w, Player issuer) {
            this.d = d; this.l = l; this.w = w;
            this.issuer = issuer == null ? null : issuer.getUniqueId();
            ox = originX(d, l); oz = originZ(d, l);
            for (int cz = oz >> 4; cz <= (oz + l.d - 1) >> 4; cz++) for (int cx = ox >> 4; cx <= (ox + l.w - 1) >> 4; cx++) chunks.add(new int[] {cx, cz});
            ci = startCi = Math.max(0, Math.min(chunks.size(), plugin.data().getInt(key(d, "next-chunk"), 0)));
            baseMs = Math.max(0, plugin.data().getLong(key(d, "elapsed-ms"), 0));
            lastTen = pct() / 10;
            bar = Bukkit.createBossBar("", BarColor.YELLOW, BarStyle.SEGMENTED_10);
        }

        int pct() { return chunks.isEmpty() ? 100 : ci * 100 / chunks.size(); }
        long elapsedMs() { return baseMs + (System.nanoTime() - startNanos) / 1_000_000L; }

        String eta() {
            int done = ci - startCi;
            long ms = (System.nanoTime() - startNanos) / 1_000_000L;
            if (done <= 0 || ms < 1000) return "계산 중";
            return "약 " + clock(ms * (chunks.size() - ci) / done);
        }

        /** Issuer (when online) + every online op. */
        List<Player> audience() {
            List<Player> out = new ArrayList<>();
            for (Player p : Bukkit.getOnlinePlayers()) if (p.isOp() || p.getUniqueId().equals(issuer)) out.add(p);
            return out;
        }

        void tell(String msg) {
            for (Player p : audience()) p.sendMessage("§e[지역 건설] §f" + msg);
        }

        void ui() {
            String title = "신규 지역 건설 중 (" + d.id() + ") " + pct() + "% · " + ci + "/" + chunks.size() + " 청크";
            bar.setTitle(title);
            bar.setProgress(Math.max(0, Math.min(1, chunks.isEmpty() ? 1 : ci / (double) chunks.size())));
            List<Player> aud = audience();
            for (Player p : aud) {
                if (!bar.getPlayers().contains(p)) bar.addPlayer(p);
                p.spigot().sendMessage(ChatMessageType.ACTION_BAR, TextComponent.fromLegacyText("§e" + title + " §7· 남은 시간 " + eta()));
            }
            for (Player p : new ArrayList<>(bar.getPlayers())) if (!aud.contains(p)) bar.removePlayer(p);
        }

        void begin(boolean auto) {
            String what = auto ? "건설 재개 (서버 재시작 후) " + pct() + "%" : ci > 0 ? "건설 재개 " + pct() + "% (" + ci + "/" + chunks.size() + " 청크부터)" : "건설 시작";
            tell(what + " · " + d.name() + " (" + d.id() + "): " + l.w + " × " + l.d + " 블록, 청크 " + chunks.size() + "개 · 중심 (" + d.cx() + ", " + d.cz() + "). 서버 부하를 줄이려고 천천히 짓습니다.");
            plugin.getLogger().info("region " + d.id() + " " + (auto ? "build resumed after restart" : "build started") + " at chunk " + ci + "/" + chunks.size() + " (" + pct() + "%)");
            ui();
        }

        private void save() {
            plugin.store(key(d, "next-chunk"), ci);
            plugin.store(key(d, "elapsed-ms"), elapsedMs());
        }

        @Override public void run() {
            try {
                if (++ticks % 20 == 0) ui();
                long deadline = System.nanoTime() + BUDGET_NS;
                while (ci < chunks.size()) {
                    int[] c = chunks.get(ci);
                    if (col < 0) {
                        // prefetch the next chunks, then wait for the current one
                        if (async != null) for (int k = ci; k < Math.min(chunks.size(), ci + PREFETCH); k++) {
                            if (pending.containsKey(k)) continue;
                            int[] p = chunks.get(k);
                            try { pending.put(k, (CompletableFuture<?>) async.invoke(w, p[0], p[1], true)); }
                            catch (ReflectiveOperationException | RuntimeException ex) { pending.put(k, CompletableFuture.completedFuture(null)); }
                        }
                        CompletableFuture<?> f = pending.get(ci);
                        if (f != null && !f.isDone() && ++waitTicks < 100) return;
                        if (f != null && !f.isDone()) {
                            plugin.getLogger().warning("region " + d.id() + ": async chunk load stalled at " + c[0] + "," + c[1] + "; loading synchronously");
                            async = null; // stop prefetching; the remaining chunks load synchronously
                            pending.clear();
                        }
                        waitTicks = 0;
                        pending.remove(ci);
                        if (!w.isChunkLoaded(c[0], c[1])) w.getChunkAt(c[0], c[1]).load(true);
                        w.addPluginChunkTicket(c[0], c[1], plugin);
                        ticket = true;
                        col = 0;
                    }
                    // columns of this chunk that lie inside the region
                    while (col < 256) {
                        int wx = (c[0] << 4) + (col & 15), wz = (c[1] << 4) + (col >> 4);
                        col++;
                        int lx = wx - ox, lz = wz - oz;
                        if (lx < 0 || lz < 0 || lx >= l.w || lz >= l.d) continue;
                        blocks += column(w, l, wx, wz, lz * l.w + lx);
                        if (System.nanoTime() > deadline) return;
                    }
                    if (ticket) { w.removePluginChunkTicket(c[0], c[1], plugin); ticket = false; }
                    col = -1;
                    ci++;
                    if (++sinceSave >= 8 || ci == chunks.size()) { sinceSave = 0; save(); }
                    int ten = pct() / 10;
                    if (ten != lastTen && ci < chunks.size()) {
                        lastTen = ten;
                        tell("건설 중 " + ten * 10 + "% · " + d.id() + " " + ci + "/" + chunks.size() + " 청크 · 남은 시간 " + eta());
                        plugin.getLogger().info("region " + d.id() + " build " + ten * 10 + "% (" + ci + "/" + chunks.size() + " chunks, eta " + eta() + ")");
                    }
                    if (System.nanoTime() > deadline) return;
                }
                finish(true, null);
            } catch (RuntimeException ex) {
                plugin.getLogger().severe("region " + d.id() + " build failed at chunk " + ci + ": " + ex);
                ex.printStackTrace();
                finish(false, ex);
            }
        }

        private void stop() {
            try { cancel(); } catch (IllegalStateException ignored) { }
            if (ticket && ci < chunks.size()) { int[] c = chunks.get(ci); w.removePluginChunkTicket(c[0], c[1], plugin); ticket = false; }
            bar.removeAll();
            if (job == this) job = null;
        }

        /** Server stop: progress stays stored and {@value #K_BUILDING} stays set, so the next start resumes. */
        void pause() {
            save();
            stop();
            tell("건설 일시 정지 " + pct() + "% (" + d.id() + " " + ci + "/" + chunks.size() + " 청크) · 서버가 다시 켜지면 자동으로 이어서 짓습니다.");
            plugin.getLogger().info("region " + d.id() + " build paused at chunk " + ci + "/" + chunks.size() + " (" + pct() + "%), resumes on next start");
        }

        private void finish(boolean ok, RuntimeException ex) {
            stop();
            plugin.store(K_BUILDING, null);
            if (!ok) {
                save();
                tell("§c" + d.name() + " 건설 중 오류 (" + ex + ") " + pct() + "%. 다시 /pipilife maps buildregion " + d.id() + " 를 실행하면 이어서 짓습니다.");
                return;
            }
            long took = elapsedMs();
            plugin.store(key(d, "next-chunk"), null);
            plugin.store(key(d, "elapsed-ms"), null);
            plugin.store(key(d, "built"), true);
            plugin.store(key(d, "layout-crc"), Long.toHexString(l.crc));
            plugin.getLogger().info("region " + d.id() + " built: " + blocks + " blocks this session, took " + clock(took));
            tell("§a건설 완료 · 소요 " + clock(took) + " §f· " + d.name() + " · /pipilife maps visit region " + d.id());
        }
    }

    /** World#getChunkAtAsync(int, int, boolean) of the Paper API when present (looked up on the Bukkit interface, not NMS). */
    private static Method asyncChunkMethod() {
        try { return World.class.getMethod("getChunkAtAsync", int.class, int.class, boolean.class); }
        catch (NoSuchMethodException | RuntimeException ex) { return null; }
    }

    /**
     * Writes one layout column (every y from the layout's y0 to its top, air runs included) and clears everything of the old
     * column above it up to the WORLD_SURFACE heightmap top (highest non-air block, so tall old towers / roofs / floating parts of
     * a previous build go too); returns the number of blocks set.
     */
    private static int column(World w, Layout l, int wx, int wz, int c) {
        int oldTop = w.getHighestBlockYAt(wx, wz, HeightMap.WORLD_SURFACE);
        int[] pos = {l.start[c]};
        int runs = varint(l.cols, pos), y = l.y0, n = 0;
        for (int r = 0; r < runs; r++) {
            BlockData data = l.pal[varint(l.cols, pos)];
            int len = varint(l.cols, pos);
            for (int k = 0; k < len; k++, y++) { w.getBlockAt(wx, y, wz).setBlockData(data, false); n++; }
        }
        for (; y <= oldTop; y++) {
            Block b = w.getBlockAt(wx, y, wz);
            if (!b.getType().isAir()) { b.setType(Material.AIR, false); n++; }
        }
        return n;
    }

    /** True when (x, z) of the wild world lies in one of the region squares. */
    private boolean inRegion(World w, int x, int z) {
        if (w == null || !w.getName().equals(plugin.wildWorldName())) return false;
        for (Def d : DEFS) if (Math.abs(x - d.cx()) <= 170 && Math.abs(z - d.cz()) <= 170) return true;
        return false;
    }

    // sculk decor must stay decor: no vibrations, no wardens
    @EventHandler(priority = EventPriority.HIGH, ignoreCancelled = true)
    public void sculkVibration(BlockReceiveGameEvent e) {
        Material m = e.getBlock().getType();
        String name = m.name();
        if (!(name.equals("SCULK_SENSOR") || name.equals("CALIBRATED_SCULK_SENSOR") || name.equals("SCULK_SHRIEKER"))) return;
        if (inRegion(e.getBlock().getWorld(), e.getBlock().getX(), e.getBlock().getZ())) e.setCancelled(true);
    }

    @EventHandler(priority = EventPriority.HIGH, ignoreCancelled = true)
    public void noWarden(CreatureSpawnEvent e) {
        if (e.getEntityType() != EntityType.WARDEN) return;
        Location l = e.getLocation();
        if (inRegion(l.getWorld(), l.getBlockX(), l.getBlockZ())) e.setCancelled(true);
    }

    // ================================================================== MythicMobs example mobs guard

    private static final java.util.Set<String> EXAMPLE_MYTHIC = java.util.Set.of("Skeleton King", "Skeletal Knight", "Skeletal Minion");

    private boolean blockExampleMythic() { return plugin.getConfig().getBoolean("block-example-mythic-mobs", true); }

    /** MythicMobs names its mobs right after the spawn: checked one tick later, all spawns of a tick in one task. */
    private void queueMythicCheck(org.bukkit.entity.Entity e) {
        if (e instanceof Player) return;
        if (mythicCheck.isEmpty()) Bukkit.getScheduler().runTask(plugin, () -> {
            int removed = 0;
            for (org.bukkit.entity.Entity en : mythicCheck) {
                if (!en.isValid()) continue;
                String name = en.getCustomName();
                if (name == null) continue;
                String plain = org.bukkit.ChatColor.stripColor(name).trim();
                if (EXAMPLE_MYTHIC.contains(plain)) { en.remove(); removed++; }
            }
            mythicCheck.clear();
            if (removed > 0) plugin.getLogger().info("MythicMobs 예제 몹 " + removed + "마리 제거 (block-example-mythic-mobs)");
        });
        mythicCheck.add(e);
    }

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void exampleMythicSpawn(CreatureSpawnEvent e) {
        if (blockExampleMythic()) queueMythicCheck(e.getEntity());
    }

    @EventHandler
    public void exampleMythicLoad(org.bukkit.event.world.EntitiesLoadEvent e) {
        if (!blockExampleMythic()) return;
        for (org.bukkit.entity.Entity en : e.getEntities()) if (en instanceof org.bukkit.entity.LivingEntity) queueMythicCheck(en);
    }

