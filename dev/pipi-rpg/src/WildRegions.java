/**
 * The main wild world ({@code wild-world}, vanilla generated):
 * <ul>
 * <li>three warp stones around the origin (category 야생) on natural ground. They are public waypoints ({@code public: true} in
 * warps.yml): unlocked for everybody and registered for every player (online ones at startup, the rest on join). Placed once
 * automatically on startup (data flag {@value #K_PLACED}) or by {@code /pipilife maps wildstones}.</li>
 * <li>three hand-designed 330 x 330 "continents" (nw / ne / se) built by {@code /pipilife maps buildregion <id>} from the layouts in
 * the plugin jar ({@code regions/<id>.bin}, generated by dev/art/regions/&lt;id&gt;/gen.mjs). The build walks the region chunk by
 * chunk (async chunk load when the server API has it), writes the layout's columns within a per-tick time budget and clears the old
 * terrain above them. Progress is stored so an interrupted build resumes (automatically after a restart: data
 * {@value #K_BUILDING}); the issuer and online ops see a boss bar / action bar / chat progress. The regions have no warp stones and are not on any map.
 * They are resource-gathering land (natural terrain, trails, a few lone houses); each has one sculk zone with a boss-room
 * entrance whose marker block is in the layout ({@link #entranceLocation(String)}). A region built from an older layout than the
 * jar's (CRC stored on completion) is rebuilt by a plain {@code buildregion <id>}.</li>
 * </ul>
 * Sculk sensors / shriekers inside the regions never react (vibrations are cancelled) and wardens never spawn there.
 */
