package dev.pipi.life;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.File;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.util.function.BooleanSupplier;
import org.bukkit.*;
import org.bukkit.block.BlockFace;
import org.bukkit.block.data.BlockData;
import org.bukkit.entity.ArmorStand;
import org.bukkit.entity.ItemFrame;
import org.bukkit.entity.Player;
import org.bukkit.inventory.ItemStack;
import org.bukkit.scheduler.BukkitRunnable;

/**
 * NPC town world (pipi_town, shown as "마을"): an island traced from a hand-drawn sketch with a plaza warp stone and four
 * themed buildings (alchemist tower, forge, market, armory). Everything comes from town_layout.json (plugin jar resource,
 * generated by dev/art/town/gen.mjs): ground surface rows, structure block runs, entities (item frames, armor stands),
 * warp stones and NPC spots. Built in batches with {@code /pipilife maps buildtown}; refuses when the world already exists.
 */
final class TownMap {
    static final String WORLD = "pipi_town";
    private static final int SEA_FLOOR = 56, SEA_TOP = 61, BUDGET = 6000;
    private static final String FLAT = """
        {"biome":"minecraft:plains","layers":[{"block":"minecraft:bedrock","height":1},
        {"block":"minecraft:stone","height":117},{"block":"minecraft:sand","height":2},
        {"block":"minecraft:water","height":6}],"features":false,"lakes":false,"structure_overrides":[]}
        """;

    record Stone(String id, String name, int x, int y, int z, float yaw) {}
    record Npc(String role, int x, int y, int z, float yaw) {}

    private final PipiLife plugin;
    private boolean building, repairing;
    private JsonObject root;

    TownMap(PipiLife plugin) { this.plugin = plugin; }

    boolean exists() {
        return Bukkit.getWorld(WORLD) != null || new File(Bukkit.getWorldContainer(), WORLD + "/level.dat").isFile();
    }

    World open() {
        World loaded = Bukkit.getWorld(WORLD);
        if (loaded != null) return loaded;
        if (!new File(Bukkit.getWorldContainer(), WORLD + "/level.dat").isFile()) return null;
        return Bukkit.createWorld(new WorldCreator(WORLD));
    }

    private boolean load() {
        if (root != null) return true;
        try (InputStream in = plugin.getResource("town_layout.json")) {
            if (in == null) return false;
            root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            return true;
        } catch (Exception ex) {
            plugin.getLogger().severe("town layout load failed: " + ex);
            return false;
        }
    }

    Location spawn(World world) {
        if (!load()) return new Location(world, 0.5, 65, 4.5, 180, 0);
        JsonObject s = root.getAsJsonObject("spawn");
        return new Location(world, s.get("x").getAsDouble(), s.get("y").getAsDouble(), s.get("z").getAsDouble(), s.get("yaw").getAsFloat(), 0);
    }

    List<Stone> stones() {
        List<Stone> out = new ArrayList<>();
        if (!load()) return out;
        for (JsonElement e : root.getAsJsonArray("warps")) {
            JsonObject o = e.getAsJsonObject();
            if (!"town_plaza".equals(o.get("id").getAsString())) continue; // only the plaza stone is kept (building stones removed on purpose)
            out.add(new Stone(o.get("id").getAsString(), o.get("name").getAsString(), o.get("x").getAsInt(), o.get("y").getAsInt(), o.get("z").getAsInt(), o.get("yaw").getAsFloat()));
        }
        return out;
    }

    List<Npc> npcSpots() {
        List<Npc> out = new ArrayList<>();
        if (!load()) return out;
        for (JsonElement e : root.getAsJsonArray("npcs")) {
            JsonObject o = e.getAsJsonObject();
            out.add(new Npc(o.get("role").getAsString(), o.get("x").getAsInt(), o.get("y").getAsInt(), o.get("z").getAsInt(), o.get("yaw").getAsFloat()));
        }
        return out;
    }

    static void rules(World world) {
        world.setGameRule(GameRule.DO_MOB_SPAWNING, false);
        world.setGameRule(GameRule.DO_DAYLIGHT_CYCLE, false);
        world.setGameRule(GameRule.DO_WEATHER_CYCLE, false);
        world.setGameRule(GameRule.DO_FIRE_TICK, false);
        world.setGameRule(GameRule.MOB_GRIEFING, false);
        world.setStorm(false);
        world.setTime(6000);
    }

    /** Layout block-state strings must carry exactly one namespace: strips doubled ones ("minecraft:minecraft:oak_fence[...]"). */
    static String normalizeState(String state) {
        String s = state.trim();
        while (s.startsWith("minecraft:minecraft:")) s = s.substring("minecraft:".length());
        return s;
    }

    /** Parsed layout palette; entries that Bukkit cannot parse stay null (logged once each). Index 0 is unused. */
    private BlockData[] palette() {
        JsonArray palJson = root.getAsJsonArray("pal");
        BlockData[] pal = new BlockData[palJson.size()];
        for (int i = 1; i < pal.length; i++) {
            String s = normalizeState(palJson.get(i).getAsString());
            try { pal[i] = Bukkit.createBlockData(s); }
            catch (IllegalArgumentException ex) { plugin.getLogger().warning("town: unknown block state " + s + ", skipped"); }
        }
        return pal;
    }

    /**
     * Re-applies layout structure cells that are air in the world but should hold a block (e.g. fences / walls / bars lost to the
     * old doubled-namespace parse bug). Never touches non-air cells, so it is idempotent and keeps player/admin edits. Batched.
     */
    void repair(Player player) {
        if (building || repairing) { player.sendMessage("마을 맵 작업이 이미 진행 중입니다."); return; }
        World world = open();
        if (world == null) { player.sendMessage("먼저 /pipilife maps buildtown을 실행하세요."); return; }
        if (!load()) { player.sendMessage("§c플러그인 안의 town_layout.json을 읽지 못했습니다."); return; }
        final BlockData[] pal = palette();
        JsonArray runsJson = root.getAsJsonArray("runs");
        final int[] runs = new int[runsJson.size()];
        for (int i = 0; i < runs.length; i++) runs[i] = runsJson.get(i).getAsInt();
        final int runCount = runs.length / 5;
        repairing = true;
        player.sendMessage("§e마을 맵 복구 시작: 구조물 " + runCount + "줄을 검사합니다 (비어 있는 칸만 채움).");
        new BukkitRunnable() {
            private int run, offset, fixed, lastPct = -1;
            @Override public void run() {
                try {
                    int budget = BUDGET;
                    while (budget > 0 && run < runCount) {
                        int i = run * 5, x = runs[i], y = runs[i + 1], z = runs[i + 2], len = runs[i + 3];
                        BlockData data = pal[runs[i + 4]];
                        if (data == null || data.getMaterial().isAir()) { run++; offset = 0; budget--; continue; }
                        while (offset < len && budget > 0) {
                            org.bukkit.block.Block b = world.getBlockAt(x + offset++, y, z);
                            budget--;
                            if (b.getType().isAir()) { b.setBlockData(data, false); fixed++; }
                        }
                        if (offset >= len) { run++; offset = 0; }
                    }
                    int pct = run * 100 / Math.max(1, runCount);
                    if (run < runCount) {
                        if (pct / 20 != lastPct / 20) { lastPct = pct; player.sendMessage("§7마을 맵 복구 " + pct + "%"); }
                        return;
                    }
                    world.save();
                    plugin.getLogger().info("town repair: " + fixed + " blocks restored");
                    player.sendMessage("§a마을 맵 복구 완료: " + fixed + "칸을 채웠습니다.");
                } catch (RuntimeException ex) {
                    plugin.getLogger().severe("town repair failed: " + ex);
                    ex.printStackTrace();
                    player.sendMessage("§c마을 맵 복구 중 오류가 발생했습니다. 콘솔을 확인하세요.");
                }
                repairing = false;
                cancel();
            }
        }.runTaskTimer(plugin, 1, 1);
    }

    /** Builds the world; {@code finish} runs when everything is placed (registers NPCs / warp stones) and returns success. */
    void build(Player player, BooleanSupplier finish) {
        if (building) { player.sendMessage("마을 맵을 만드는 중입니다."); return; }
        if (exists() || new File(Bukkit.getWorldContainer(), WORLD).exists()) {
            player.sendMessage("§c" + WORLD + " 월드가 이미 있습니다. 새로 만들려면 월드 폴더를 지운 서버에서 실행하세요.");
            return;
        }
        if (!load()) { player.sendMessage("§c플러그인 안의 town_layout.json을 읽지 못했습니다."); return; }
        building = true;
        final int width = root.get("width").getAsInt(), height = root.get("height").getAsInt();
        final int ox = root.get("originX").getAsInt(), oz = root.get("originZ").getAsInt(), baseY = root.get("baseY").getAsInt();
        World world = Bukkit.createWorld(new WorldCreator(WORLD).type(WorldType.FLAT).generatorSettings(FLAT).generateStructures(false));
        if (world == null) { building = false; player.sendMessage("§c월드를 생성하지 못했습니다."); return; }
        world.setSpawnLocation(0, baseY + 2, 4);
        rules(world);

        // ground surface per column (0 = water)
        JsonArray surfPal = root.getAsJsonArray("surfPal");
        Material[] surfMat = new Material[surfPal.size()];
        for (int i = 1; i < surfMat.length; i++) {
            Material m = Material.matchMaterial(surfPal.get(i).getAsString().toUpperCase(Locale.ROOT));
            surfMat[i] = m != null ? m : Material.GRASS_BLOCK;
        }
        byte[][] surf = new byte[height][width];
        JsonArray rows = root.getAsJsonArray("rows");
        for (int z = 0; z < height; z++) {
            String row = rows.get(z).getAsString();
            int x = 0;
            for (int i = 0; i < row.length(); ) {
                char ch = row.charAt(i++);
                int n = 0;
                while (i < row.length() && Character.isDigit(row.charAt(i))) n = n * 10 + (row.charAt(i++) - '0');
                byte t = ch == 'w' ? 0 : (byte) (ch - 'a' + 1);
                for (int k = 0; k < n && x < width; k++) surf[z][x++] = t;
            }
        }
        byte[][] wd = new byte[height][width];
        ArrayDeque<int[]> queue = new ArrayDeque<>();
        for (int z = 0; z < height; z++) for (int x = 0; x < width; x++) {
            if (surf[z][x] == 0) queue.add(new int[] {x, z}); else wd[z][x] = 9;
        }
        while (!queue.isEmpty()) {
            int[] c = queue.poll();
            int d = wd[c[1]][c[0]];
            if (d >= 5) continue;
            for (int dz = -1; dz <= 1; dz++) for (int dx = -1; dx <= 1; dx++) {
                int nx = c[0] + dx, nz = c[1] + dz;
                if (nx < 0 || nz < 0 || nx >= width || nz >= height || wd[nz][nx] <= d + 1) continue;
                wd[nz][nx] = (byte) (d + 1);
                queue.add(new int[] {nx, nz});
            }
        }
        // structure palette + runs
        BlockData[] pal = palette();
        for (int i = 1; i < pal.length; i++) if (pal[i] == null) pal[i] = Material.AIR.createBlockData();
        JsonArray runsJson = root.getAsJsonArray("runs");
        int[] runs = new int[runsJson.size()];
        for (int i = 0; i < runs.length; i++) runs[i] = runsJson.get(i).getAsInt();
        final int cells = width * height, runCount = runs.length / 5;
        player.sendMessage("§e마을 맵 생성 시작: " + width + " × " + height + " 블록, 구조물 " + runCount + "줄.");
        new BukkitRunnable() {
            private int cursor, run, ent, lastPct = -1;
            private final JsonArray ents = root.getAsJsonArray("entities");
            @Override public void run() {
                try {
                    int budget = BUDGET;
                    while (budget > 0 && cursor < cells) budget -= column(world, cursor % width, cursor++ / width);
                    while (budget > 0 && cursor >= cells && run < runCount) {
                        int i = run++ * 5, x = runs[i], y = runs[i + 1], z = runs[i + 2], len = runs[i + 3];
                        BlockData data = pal[runs[i + 4]];
                        for (int k = 0; k < len; k++) world.getBlockAt(x + k, y, z).setBlockData(data, false);
                        budget -= len + 1;
                    }
                    long total = (long) cells + runCount;
                    int pct = (int) ((cursor + (long) run * (cursor >= cells ? 1 : 0)) * 100L / total);
                    if (pct / 10 != lastPct / 10) { lastPct = pct; player.sendMessage("§7마을 맵 진행 " + pct + "%"); }
                    if (cursor < cells || run < runCount) return;
                    while (ent < ents.size()) entity(world, ents.get(ent++).getAsJsonObject());
                    world.save();
                    player.sendMessage(finish.getAsBoolean()
                        ? "§a마을 맵 완성 (워프석·NPC 등록). /pipilife maps visit town"
                        : "§e맵은 완성됐지만 NPC/워프석 등록 중 문제가 있었습니다. /pipilife maps npcstown, warptown을 실행하세요.");
                } catch (RuntimeException ex) {
                    plugin.getLogger().severe("town build failed: " + ex);
                    ex.printStackTrace();
                    player.sendMessage("§c맵 생성 중 오류가 발생했습니다. 콘솔을 확인하세요.");
                }
                building = false;
                cancel();
            }

            private int column(World w, int gx, int gz) {
                int ty = surf[gz][gx];
                if (ty == 0) return 1;
                int x = gx + ox, z = gz + oz, d = wd[gz][gx], n = 0;
                int top = d == 1 ? SEA_TOP : d == 2 ? SEA_TOP + 1 : baseY;
                boolean beach = d <= 2;
                for (int y = SEA_FLOOR; y < top; y++) {
                    Material m = beach && y >= top - 2 ? Material.SAND : y >= top - 3 ? Material.DIRT : Material.STONE;
                    w.getBlockAt(x, y, z).setType(m, false); n++;
                }
                w.getBlockAt(x, top, z).setType(beach ? Material.SAND : surfMat[ty], false);
                return n + 1;
            }
        }.runTaskTimer(plugin, 1, 1);
    }

    private static Material mat(JsonObject o, String key) {
        if (!o.has(key)) return null;
        return Material.matchMaterial(o.get(key).getAsString());
    }

    private void entity(World world, JsonObject o) {
        String type = o.get("t").getAsString();
        Location at = new Location(world, o.get("x").getAsInt() + 0.5, o.get("y").getAsInt(), o.get("z").getAsInt() + 0.5);
        at.getChunk().load();
        if (type.equals("frame")) {
            BlockFace face;
            try { face = BlockFace.valueOf(o.get("f").getAsString().toUpperCase(Locale.ROOT)); } catch (IllegalArgumentException ex) { return; }
            Material item = mat(o, "item");
            try {
                world.spawn(at, ItemFrame.class, frame -> {
                    frame.setFacingDirection(face, true);
                    if (item != null) frame.setItem(new ItemStack(item), false);
                    frame.setFixed(true);
                    frame.setInvulnerable(true);
                });
            } catch (IllegalArgumentException ex) { plugin.getLogger().warning("town: item frame at " + at + " could not be placed: " + ex.getMessage()); }
        } else if (type.equals("stand")) {
            at.setYaw(o.get("yaw").getAsFloat());
            world.spawn(at, ArmorStand.class, stand -> {
                stand.setArms(true);
                stand.setBasePlate(false);
                stand.setGravity(false);
                stand.setInvulnerable(true);
                stand.setPersistent(true);
                var eq = stand.getEquipment();
                Material h = mat(o, "head"), c = mat(o, "chest"), l = mat(o, "legs"), f = mat(o, "feet"), hand = mat(o, "hand");
                if (h != null) eq.setHelmet(new ItemStack(h));
                if (c != null) eq.setChestplate(new ItemStack(c));
                if (l != null) eq.setLeggings(new ItemStack(l));
                if (f != null) eq.setBoots(new ItemStack(f));
                if (hand != null) eq.setItemInMainHand(new ItemStack(hand));
            });
        }
    }
}
